function completedLessons(slug) {
  try { return JSON.parse(localStorage.getItem(`manukura-complete-${slug}`) || "[]"); }
  catch { return []; }
}

function bindCourseInteractions(route, slug) {
  document.querySelectorAll("[data-course-complete]").forEach(input=>input.addEventListener("change",()=>{
    const area=input.dataset.courseComplete;
    const completed=new Set(completedLessons(area));
    const lesson=Number(input.dataset.lesson);
    input.checked ? completed.add(lesson) : completed.delete(lesson);
    localStorage.setItem(`manukura-complete-${area}`,JSON.stringify([...completed].sort((a,b)=>a-b)));
    const banner=document.querySelector(".progress-wrap");
    if (banner) {
      const count=completed.size, total=courseInfo[area].lessons.length, percent=Math.round(count/total*100);
      banner.querySelector("strong").textContent=`${count} of ${total} lessons complete`;
      banner.querySelector("span").textContent=`${percent}%`;
      banner.querySelector("progress").value=percent;
    }
  }));
  document.querySelectorAll("[data-variable]").forEach(button=>button.addEventListener("click",()=>{
    const feedback=document.querySelector(".interactive-feedback");
    feedback.textContent=button.dataset.variable === "correct" ? "Correct. Water temperature is deliberately changed." : "Try again. Ask which factor the student deliberately changes.";
    feedback.className=`interactive-feedback ${button.dataset.variable === "correct" ? "correct" : "retry"}`;
  }));
  document.querySelectorAll("[data-state]").forEach(button=>button.addEventListener("click",()=>{
    const state=button.dataset.state, stage=document.querySelector("#particle-stage"), text=document.querySelector("#state-explanation");
    stage.className=`particle-stage ${state}`;
    stage.querySelectorAll("span").forEach((dot,index)=>{
      if(state === "solid") {
        dot.style.left=`${19 + (index % 6) * 11}%`;
        dot.style.top=`${54 + Math.floor(index / 6) * 10}%`;
      } else if(state === "liquid") {
        dot.style.left=`${7 + (index % 8) * 11}%`;
        dot.style.top=`${48 + Math.floor(index / 8) * 16}%`;
      } else {
        dot.style.left=`${5 + ((index * 37) % 88)}%`;
        dot.style.top=`${5 + ((index * 23) % 84)}%`;
      }
    });
    text.textContent={solid:"Particles stay close in fixed positions and vibrate.",liquid:"Particles remain close but move past one another.",gas:"Particles spread out and move freely in all directions."}[state];
  }));
  const firstState=document.querySelector('[data-state="solid"]');
  if(firstState) firstState.click();
  const organelleText={"Cell wall":"A strong outer layer that supports and protects the plant cell.","Nucleus":"Contains genetic information and controls cell activities.","Chloroplast":"Contains chlorophyll and absorbs light for photosynthesis.","Vacuole":"Contains cell sap and helps support the cell."};
  document.querySelectorAll("[data-organelle]").forEach(button=>button.addEventListener("click",()=>document.querySelector("#organelle-explanation").textContent=organelleText[button.dataset.organelle]));
  const amp=document.querySelector("#wave-amplitude"), freq=document.querySelector("#wave-frequency");
  if (amp && freq) {
    const draw=()=>{
      const a=Number(amp.value), f=Number(freq.value), points=[];
      for(let x=0;x<=600;x+=5) points.push(`${x},${90-a*Math.sin(x/600*Math.PI*2*f)}`);
      document.querySelector("#wave-path").setAttribute("d",`M${points.join(" L")}`);
      document.querySelector("#wave-explanation").textContent=`Amplitude ${a}, frequency ${f} cycle${f===1?"":"s"}. Increasing amplitude makes a sound louder. Increasing frequency raises pitch.`;
    };
    amp.addEventListener("input",draw); freq.addEventListener("input",draw); draw();
  }
  if (route === "revision" && slug) bindInteractions(slug);
  const build=document.querySelector("#build-exam");
  if (build) build.addEventListener("click",buildMixedExam);
  document.querySelectorAll("[data-exam-check]").forEach(box=>{
    box.checked=localStorage.getItem(`manukura-exam-${box.dataset.examCheck}`)==="1";
    box.addEventListener("change",()=>localStorage.setItem(`manukura-exam-${box.dataset.examCheck}`,box.checked?"1":"0"));
  });
}

function buildMixedExam() {
  const all=[];
  Object.entries(units).forEach(([slug,u])=>u.quiz.forEach(q=>all.push({...q,area:u.title,slug})));
  const selected=[];
  Object.keys(units).forEach(slug=>{
    const pool=all.filter(q=>q.slug===slug).sort(()=>Math.random()-.5);
    selected.push(...pool.slice(0,5));
  });
  selected.sort(()=>Math.random()-.5);
  const target=document.querySelector("#exam-quiz");
  target.innerHTML=`<form class="mixed-quiz">${selected.map((q,i)=>`<fieldset><legend>${i+1}. <small>${q.area}</small>${q.q}</legend>${q.options.map((o,j)=>`<label><input type="radio" name="mixed-${i}" value="${j}"> ${o}</label>`).join("")}<p class="mixed-feedback" hidden></p></fieldset>`).join("")}<button class="button" type="submit">Mark this set</button><strong class="mixed-score" aria-live="polite"></strong></form>`;
  target.querySelector("form").addEventListener("submit",event=>{
    event.preventDefault(); let score=0;
    selected.forEach((q,i)=>{
      const chosen=target.querySelector(`input[name="mixed-${i}"]:checked`), feedback=target.querySelectorAll(".mixed-feedback")[i];
      const correct=chosen && Number(chosen.value)===q.a; if(correct) score++;
      feedback.hidden=false; feedback.textContent=correct?`Correct. ${q.why}`:`Review this one. ${q.why}`;
    });
    target.querySelector(".mixed-score").textContent=` ${score} / ${selected.length}`;
  });
}

function renderCourseSite() {
  const parts=(location.hash.slice(1)||"home").split("/");
  let [route,slug,anchor]=parts;
  if (units[route]) { slug=route; route="learn"; }
  const pages={home:courseHomePage,learn:()=>slug&&units[slug]?learningUnitPage(slug):learningHubPage(),revision:()=>slug&&units[slug]?revisionUnitPage(slug):revisionHubPage(),exam:examPage,assessment:assessmentPage};
  const renderer=pages[route]||courseHomePage;
  document.querySelector("#main").innerHTML=renderer();
  document.querySelectorAll("#main-nav a").forEach(a=>a.toggleAttribute("aria-current",a.getAttribute("href")===`#${route}`));
  document.querySelector("#main-nav").classList.remove("open");
  document.querySelector(".menu-button").setAttribute("aria-expanded","false");
  bindCourseInteractions(route,slug);
  requestAnimationFrame(()=>{
    let target=null;
    if(anchor) target=document.getElementById(`${slug}-${anchor}`)||document.getElementById(anchor);
    if(target) target.scrollIntoView({behavior:"smooth",block:"start"}); else window.scrollTo({top:0});
  });
}

window.addEventListener("hashchange",renderCourseSite);
renderCourseSite();
